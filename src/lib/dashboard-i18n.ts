export type DashMessages = (typeof dashMessages)["nl"];

export async function getDashLocale(): Promise<DashLocale> {
  const store = await cookies();
  const value = store.get(DASH_LOCALE_COOKIE)?.value;
  return value === "en" ? "en" : "nl";
}

export async function getDashMessages(): Promise<{
  locale: DashLocale;
  messages: DashMessages;
}> {
  const locale = await getDashLocale();
  return { locale, messages: dashMessages[locale] };
}
